"use strict";
/**
 * tokens.css and the @font-face rules for the design-system bundle, built from
 * DESIGN.md's waterline block. Split out of build.js so that file stays under
 * the staged-file size gate.
 */
const path = require("path");

const manifest = require("../../fonts/manifest.json");
const fontSources = [
  ["src/assets/fonts/homepage/poppins-400-latin.woff2", "Poppins", 400, "normal"],
  ["src/assets/fonts/homepage/poppins-500-latin.woff2", "Poppins", 500, "normal"],
  ["src/assets/fonts/homepage/poppins-600-latin.woff2", "Poppins", 600, "normal"],
  ["src/assets/fonts/homepage/poppins-700-latin.woff2", "Poppins", 700, "normal"],
  ["src/assets/fonts/guest/instrument-serif.woff2", "Instrument Serif", 400, "normal"],
  ["src/assets/fonts/guest/instrument-serif-italic.woff2", "Instrument Serif", 400, "italic"],
];
const fonts = fontSources.flatMap(([src, family, weight, style]) =>
  Object.values(manifest[path.basename(src)].parts).map(part =>
    [part.path, family, weight, style, part.legacy_unrestricted ? null : part.unicode_range]));
// `prefix` is the path from the consuming file to waterline/fonts/.
function fontFace(prefix) {
  return fonts
    .map(([src, family, weight, style, range]) =>
      `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;src:url('${prefix}${path.basename(src)}') format('woff2');${range ? `unicode-range:${range}` : ''}}`
    )
    .join("\n");
}

// Spacing, radius, motion and shadow scales from DESIGN.md, as the design system's --wl-* tokens.
function scaleTokens({ space = {}, rounded = {}, motion = {}, shadow = {} }) {
  const lines = [];
  for (const [k, v] of Object.entries(space)) lines.push(`--wl-space-${k}:${v};`);
  for (const [k, v] of Object.entries(rounded)) if (k !== "button") lines.push(`--wl-radius-${k}:${v};`);
  for (const [k, v] of Object.entries(motion.duration || {})) lines.push(`--wl-dur-${k}:${v};`);
  for (const [k, v] of Object.entries(motion.easing || {})) lines.push(`--wl-ease-${k}:${v};`);
  for (const [k, v] of Object.entries(shadow)) lines.push(`--wl-shadow-${k}:${v};`);
  return lines.map((line) => `  ${line}`).join("\n");
}

function tokensCss(wl, stamp) {
  const C = wl.colors;
  const T = wl.typography;
  return `/* Generated by scripts/design/design-sync/build.js from DESIGN.md (system block)
   at ${stamp}. Do not edit by hand; edit DESIGN.md and re-run the build. */
:root{
  --wl-bg:${C.bg};             /* every page canvas */
  --wl-surface:${C.surface};   /* the only fill besides white */
  --wl-ink:${C.ink};           /* text, icons, selected chips */
  --wl-muted:${C.muted};       /* secondary text */
  --wl-line:${C.line};         /* dividers, card outlines */
  --wl-accent:${C.accent};     /* the one action color */
  --wl-paper:${C.paper};       /* canvas alias */
  --wl-rule:${C.rule};         /* line alias */
  --wl-soft:${C.soft};         /* surface alias */
  --wl-font-display:'${T.display.fontFamily}',Georgia,serif;
  --wl-font-body:${T.body.fontFamily},system-ui,sans-serif;
  --wl-display-weight:${T.display.fontWeight};
  --wl-display-lh:${T.display.lineHeight};
  --wl-display-ls:${T.display.letterSpacing};
  --wl-h1:${T.display.h1};
  --wl-body-size:${T.body.fontSize};
  --wl-body-lh:${T.body.lineHeight};
  --wl-label-size:${T.label.fontSize};
  --wl-label-ls:${T.label.letterSpacing};
  --wl-radius-button:${wl.rounded.button};
  --wl-control-min:48px; /* buttons; 44px is the mobile floor (F2) */
${scaleTokens(wl)}
}
${fontFace("fonts/")}
@font-face{font-family:Inter;font-style:normal;font-weight:100 900;font-display:swap;src:url('fonts/inter-latin-wght-3100e775e861.woff2') format('woff2');}
`;
}

module.exports = { fonts, fontFace, tokensCss };
